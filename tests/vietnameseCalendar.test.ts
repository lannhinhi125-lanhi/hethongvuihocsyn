import assert from 'node:assert/strict';
import { calendarDateAllowed, displayVietnameseDate, moveCalendarDate, moveCalendarMonth, parseVietnameseDate, vietnameseCalendarDays } from '../src/lib/vietnameseCalendar';
assert.equal(displayVietnameseDate('2026-09-30'), '30/09/2026');
assert.equal(parseVietnameseDate('1/9/2026'), '2026-09-01');
assert.equal(parseVietnameseDate(' 30/09/2026 '), '2026-09-30');
assert.equal(parseVietnameseDate('31/09/2026'), null);
assert.equal(parseVietnameseDate('29/02/2025'), null);
assert.equal(parseVietnameseDate('29/02/2024'), '2024-02-29');
assert.equal(parseVietnameseDate('29/02/1900'), null);
assert.equal(parseVietnameseDate('29/02/2000'), '2000-02-29');
assert.equal(parseVietnameseDate('2026-09-30'), null);
assert.equal(displayVietnameseDate(''), '');
const september = vietnameseCalendarDays('2026-09');
assert.equal(september.length, 42);
assert.equal(september[0], '2026-08-31'); // Monday, not Sunday.
assert.equal(september[1], '2026-09-01');
assert.equal(september[41], '2026-10-11');
assert.equal(new Set(september).size, 42);
assert.ok(vietnameseCalendarDays('2024-02').includes('2024-02-29'));
assert.ok(!vietnameseCalendarDays('2025-02').includes('2025-02-29'));
assert.equal(moveCalendarMonth('2026-01-31', 1), '2026-02-28');
assert.equal(moveCalendarMonth('2024-01-31', 1), '2024-02-29');
assert.equal(moveCalendarMonth('2026-01-15', -1), '2025-12-15');
assert.equal(moveCalendarDate('2026-12-31', 1), '2027-01-01');
assert.equal(moveCalendarDate('2024-03-01', -1), '2024-02-29');
assert.ok(calendarDateAllowed('2026-09-01', '2026-09-01', '2026-09-30'));
assert.ok(calendarDateAllowed('2026-09-30', '2026-09-01', '2026-09-30'));
assert.ok(!calendarDateAllowed('2026-08-31', '2026-09-01', '2026-09-30'));
assert.ok(!calendarDateAllowed('2026-10-01', '2026-09-01', '2026-09-30'));
assert.ok(!calendarDateAllowed('2026-02-30'));
console.log('PASS: Vietnamese date parsing, Monday calendar, leap years, month/year boundaries and inclusive limits');
