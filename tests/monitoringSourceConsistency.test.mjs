import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
const writes = {};
globalThis.monitoringTestWrites = writes;
const helperUrl = 'data:text/javascript;base64,' + Buffer.from(stripTypeScriptTypes(readFileSync('src/lib/monitoringIncidents.ts','utf8'))).toString('base64');
const source = readFileSync('src/lib/monitoringPersistence.ts', 'utf8').replace("import { setBusinessValue } from './businessPersistence';", 'const setBusinessValue = (key, value) => {globalThis.monitoringTestWrites[key] = value;};').replace("'./monitoringIncidents'",JSON.stringify(helperUrl));
const js = stripTypeScriptTypes(source);
const { storedMonitoringSession, persistMonitoringChanges } = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
const base = {sessionCode:'old-schedule',classCode:'CLS',sessionDate:'2026-10-17',timeSlot:'18:00-19:30',checkinTime:'18:08:00',checkinAt:'stale',checkoutAt:'stale'};
const lesson = {id:'REAL-ID',displayCode:'BH-000155',classId:'C',date:'2026-10-17',timeSlotId:'S',primaryTeacherId:'DEMO-001',status:'CHUA_HOC',checkinAt:null,checkoutAt:null};
const map = (rows, incidents=[]) => storedMonitoringSession(base,rows,incidents,[{id:'C',code:'CLS'}],[],[{id:'S',timeRange:'18:00 - 19:30'}],[]);
const mapped = map([lesson], [{id:'old',lessonId:lesson.id,reportedAt:'2026-10-01',content:'old'},{id:'new',lessonId:lesson.id,reportedAt:'2026-10-02',content:'new'}]);
assert.equal(mapped.sessionCode,lesson.id);
assert.equal(mapped.displayCode,'BH-000155');
assert.equal(mapped.checkinTime,null);
assert.equal(mapped.checkinAt,null);
assert.equal(mapped.checkoutAt,null);
assert.equal(mapped.incidentNote,'new');
assert.equal(map([lesson]).hasIncident,false);
const view = readFileSync('src/views/Module5_OperationsMonitoring.tsx','utf8');
assert.ok(view.includes('persistedLessons.filter(lesson => unresolvedMode ||'));
assert.ok(view.includes('setSessions(generated)'));
assert.ok(!view.includes('classes.forEach(cls =>'),'monitoring does not generate lessons from the class timetable');
const cls = {id:'C',code:'CLS',teacherId:'DEMO-001'};
const teachers = [{id:'DEMO-001',name:'Teacher'}];
const slots = [{id:'S',timeRange:'18:00 - 19:30'}];
const incidents = [{id:'INC-REAL',lessonId:lesson.id,reportedAt:'2026-10-17',content:'original'}];
const original = {...lesson,startsAt:'2026-10-17T18:05:00+07:00',endsAt:'2026-10-17T19:35:00+07:00',checkinAt:'2026-10-17T18:08:00+07:00'};
const old = storedMonitoringSession(base,[original],incidents,[cls],teachers,slots,[]);
const persist = (next, rows=[original], before=old) => persistMonitoringChanges([before],[next],rows,incidents,[cls],teachers,slots,[],'OPS');
persist({...old,checkinTime:'18:10:00'});
assert.equal(writes.dated_lessons.length,1);
assert.equal(writes.dated_lessons[0].id,lesson.id);
assert.equal(writes.dated_lessons[0].checkinAt,'2026-10-17T18:10:00+07:00');
assert.equal(writes.dated_lessons[0].startsAt,original.startsAt,'monitoring preserves actual scheduled times');
assert.deepEqual(writes.lesson_incidents,incidents,'editing attendance does not rewrite the incident');
persist({...old,checkinTime:null});
assert.equal(writes.dated_lessons[0].checkinAt,null,'clearing check-in clears the source');
persist({...old,checkoutAt:'2026-10-17T19:35:00+07:00'});
assert.equal(writes.dated_lessons[0].checkoutAt,'2026-10-17T19:35:00+07:00');
assert.throws(()=>persist({...old,lessonDiary:'changed'},[]),/Buổi học không còn tồn tại/,'monitoring cannot create a missing lesson');
const reread=storedMonitoringSession(base,writes.dated_lessons,incidents,[cls],teachers,slots,[]);
assert.equal(reread.checkoutAt,writes.dated_lessons[0].checkoutAt,'source changes flow back into monitoring');
delete globalThis.monitoringTestWrites;
console.log('PASS: monitoring uses saved lesson identity, source timestamps, and latest linked incident');
