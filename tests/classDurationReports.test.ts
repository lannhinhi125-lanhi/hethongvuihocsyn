import assert from 'node:assert/strict';
import {classEndDate} from '../src/lib/classDuration';
import {allReportDatasets} from '../src/lib/allReportDatasets';
import {reportToday} from '../src/lib/customReports';
import {studentStudyEditIssue} from '../src/lib/profileEditing';
import {updateStudentRegistration} from '../src/lib/studentRegistrations';
import type {ClassItem,StudentRecord} from '../src/types';
assert.equal(classEndDate('2026-10-05',1),'2026-11-04');
assert.equal(classEndDate('2026-10-05',3),'2027-01-04');
assert.equal(classEndDate('2024-02-29',12),'2025-02-27');
assert.equal(classEndDate('2028-01-31',1),'2028-02-28');
assert.equal(classEndDate('2026-02-30',1),'');
const student={id:'S1',name:'An',grade:'G1',subject:'M',model:'solo',level:'basic',status:'Đã thôi học',scheduleSlots:[],created_at:'2026-01-01',registrations:[{subject:'M',model:'solo',level:'basic',status:'Đã thôi học',scheduleSlots:[],registeredAt:'2026-01-01',periodNumber:1}]} as StudentRecord;
const reopened=updateStudentRegistration(student,{registrations:[{...student.registrations![0],status:'Chờ xếp lớp',level:'advanced'}]});
assert.equal(reopened.id,student.id);
assert.equal(studentStudyEditIssue(student,reopened,[]),undefined);
const today=reportToday();
const shift=(days:number)=>new Date(Date.parse(today+'T00:00:00Z')+days*86400000).toISOString().slice(0,10);
const base={id:'C1',code:'C1',name:'Lớp',grade:'G1',subject:'M',level:'basic',model:'solo',studentIds:[],maxStudents:1,teacherName:'GV',schedule:'',roomLink:'',materials:[],status:'Đang học'} as ClassItem;
const classes=[{...base,endDate:today},{...base,id:'C2',code:'C2',endDate:shift(30)},{...base,id:'C3',code:'C3',endDate:shift(31)},{...base,id:'C4',code:'C4',endDate:shift(-1)},{...base,id:'C5',code:'C5',endDate:today,status:'Đã kết thúc' as const}];
const current={...reopened,registrations:[{...reopened.registrations![0],registeredAt:today,registrationKind:'RETURNING',periodNumber:2}],registrationHistory:[{...student.registrations![0],grade:'G1',endedAt:'2026-02-01',registrationKind:'FIRST'}]};
const datasets=allReportDatasets({classes,students:[current],teachers:[],lessons:[],incidents:[],evaluations:[],lookups:{}}).detail;
assert.deepEqual(datasets.find(d=>d.id==='classes_ending')!.records.map(r=>r.id),['C1','C2']);
const periods=datasets.find(d=>d.id==='student_registration_periods')!.records;
assert.equal(periods.length,2);
assert.ok(periods.every(row=>row.id==='S1'));
assert.equal(periods[1].kind,'Đăng ký học lại');
assert.equal(datasets.find(d=>d.id==='students')!.records.length,1);
console.log('PASS: calendar boundaries, same student identity, 30-day ending window, distinct registration periods');
