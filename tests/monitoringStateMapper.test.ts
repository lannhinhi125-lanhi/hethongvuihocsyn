import assert from 'node:assert/strict';
import {fromSupabaseRow,toSupabaseRow} from '../src/lib/supabaseMapper';
const progress={total:2,completed:1,state:'CHUA_DU',studentIds:['S1','S2']};
const decoded=fromSupabaseRow('dated_lessons',{madinhdanh:'STATE-1',trangthai:'DA_HOC',tiendonhanxet:progress});
assert.deepEqual(decoded.feedbackProgress,progress);
assert.deepEqual(toSupabaseRow('dated_lessons',decoded),{madinhdanh:'STATE-1',trangthai:'DA_HOC'});
const lesson=fromSupabaseRow('dated_lessons',{madinhdanh:'CLOCK-1',ngayhoc:'2026-10-23',makhunggio:'K1',batdau:'19:00:00',ketthuc:'20:00:00',vaolopluc:'2026-10-23T12:01:00Z'});
assert.equal(lesson.startsAt,'2026-10-23T19:00:00+07:00');
assert.equal(lesson.endsAt,'2026-10-23T20:00:00+07:00');
assert.deepEqual(toSupabaseRow('dated_lessons',lesson),{madinhdanh:'CLOCK-1',ngayhoc:'2026-10-23',makhunggio:'K1',vaolopluc:'2026-10-23T12:01:00Z'});
const overnight=fromSupabaseRow('dated_lessons',{madinhdanh:'CLOCK-NIGHT',ngayhoc:'2026-10-23',makhunggio:'NIGHT',batdau:'23:40:00',ketthuc:'00:53:00'});
assert.equal(overnight.endsAt,'2026-10-24T00:53:00+07:00');
assert.equal((Date.parse(String(overnight.endsAt))-Date.parse(String(overnight.startsAt)))/60000,73);
const incident=fromSupabaseRow('lesson_incidents',{madinhdanh:'SC-1',mabuoi:'B-1',manhomsuco:'GROUP-1',masuco:'NET',tensuco:'Tên từ danh mục',dotamdunglop:false,noidung:'Chi tiết riêng'});
assert.equal(incident.incidentName,'Tên từ danh mục');
assert.deepEqual(toSupabaseRow('lesson_incidents',incident),{madinhdanh:'SC-1',mabuoi:'B-1',manhomsuco:'GROUP-1',masuco:'NET',noidung:'Chi tiết riêng'});
console.log('PASS: feedback progress is read-only');
