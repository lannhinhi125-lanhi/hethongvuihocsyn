import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const source=stripTypeScriptTypes(readFileSync('src/lib/sessionAlerts.ts','utf8'));
const {isMonitoringApproved,sessionCompletionWarning}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const session={sessionDate:'2026-10-29',timeSlot:'18:00 - 19:30',checkinAt:'2026-10-29T18:00:00+07:00',checkoutAt:'2026-10-29T19:00:00+07:00'};
const now=new Date('2026-10-29T19:31:00+07:00');
const warning=sessionCompletionWarning(session,now);
assert.ok(warning);
assert.equal(isMonitoringApproved(session,warning),false);
const approved={...session,monitoringApproval:{by:'OPS',at:now.toISOString(),warning,checkinAt:session.checkinAt,checkoutAt:session.checkoutAt}};
assert.equal(isMonitoringApproved(approved,warning),true);
assert.equal(approved.checkinAt,session.checkinAt);
assert.equal(approved.checkoutAt,session.checkoutAt);
assert.equal(isMonitoringApproved({...approved,checkoutAt:'2026-10-29T18:30:00+07:00'},warning),false);
assert.equal(isMonitoringApproved(approved,'CHUA_VAO_LOP'),false);
const absent={monitoringApproval:{by:'OPS',at:now.toISOString(),warning:'CHUA_VAO_LOP',checkinAt:null,checkoutAt:null}};
assert.equal(isMonitoringApproved(absent,'CHUA_VAO_LOP'),true);
assert.equal(isMonitoringApproved({...absent,checkinAt:session.checkinAt},'CHUA_VAO_LOP'),false);
console.log('PASS: approval preserves actual timestamps and expires when attendance or warning changes.');
